import type { AppDocument } from "./app-data-context";

export type QueryIntent = "conceptual" | "factual" | "code" | "exam_prep" | "off_topic";
export type RetrievalStrategy = "Dense Vector" | "Hybrid (BM25+Dense)" | "Code Syntax Aware" | "Multi-Doc Synthesis" | "Direct Rejection";
export type RagMode = "Adaptive RAG (Auto)" | "Dense Vector" | "Hybrid (BM25+Dense)" | "Direct LLM";

export interface RetrievedChunk {
  id: string;
  docId: string;
  docName: string;
  fileType: string;
  subjectName: string;
  unit: string;
  pageNumber: number;
  content: string;
  similarityScore: number; // 0.0 to 1.0 (e.g. 0.88 = 88%)
  denseScore: number;
  bm25Score: number;
}

export interface PipelineStep {
  step: number;
  title: string;
  detail: string;
  status: "pending" | "running" | "completed";
}

export interface RagResponse {
  intent: QueryIntent;
  strategy: RetrievalStrategy;
  queryExpanded: string;
  retrievedChunks: RetrievedChunk[];
  confidenceScore: number; // 0 to 100
  hallucinationCheck: {
    passed: boolean;
    overlapScore: number; // 0.0 to 1.0
    reason: string;
  };
  answer: string;
  citations: Array<{
    id: string;
    docName: string;
    page: number;
    unit: string;
    chunkContent: string;
    similarity: number;
  }>;
  followUpSuggestions: string[];
  shouldEscalate: boolean;
  pipelineSteps: PipelineStep[];
}

// ─── Query Intent Classification ──────────────────────────────────────────────

export function classifyIntent(query: string): QueryIntent {
  const q = query.toLowerCase();

  // Off-topic check
  if (
    q.includes("movie") || q.includes("cricket") || q.includes("weather") ||
    q.includes("recipe") || q.includes("joke") || q.includes("who won") ||
    q.includes("president") || q.includes("capital of france")
  ) {
    return "off_topic";
  }

  // Code intent
  if (
    q.includes("code") || q.includes("python") || q.includes("function") ||
    q.includes("write a script") || q.includes("spark code") || q.includes("algorithm code") ||
    q.includes("class") || q.includes("syntax") || q.includes("implementation")
  ) {
    return "code";
  }

  // Exam prep intent
  if (
    q.includes("exam") || q.includes("important question") || q.includes("pyq") ||
    q.includes("syllabus") || q.includes("weightage") || q.includes("revision") ||
    q.includes("marks") || q.includes("previous year")
  ) {
    return "exam_prep";
  }

  // Factual intent
  if (
    q.includes("who created") || q.includes("when was") || q.includes("what year") ||
    q.includes("definition of") || q.includes("full form of") || q.includes("difference between") ||
    q.includes("vs") || q.includes("types of")
  ) {
    return "factual";
  }

  // Default conceptual
  return "conceptual";
}

export function selectStrategy(intent: QueryIntent, mode: RagMode): RetrievalStrategy {
  if (mode === "Direct LLM") return "Direct Rejection";
  if (mode === "Dense Vector") return "Dense Vector";
  if (mode === "Hybrid (BM25+Dense)") return "Hybrid (BM25+Dense)";

  switch (intent) {
    case "conceptual": return "Dense Vector";
    case "factual":    return "Hybrid (BM25+Dense)";
    case "code":       return "Code Syntax Aware";
    case "exam_prep":  return "Multi-Doc Synthesis";
    case "off_topic":  return "Direct Rejection";
  }
}

