function computeSimilarity(query: string, content: string, strategy: RetrievalStrategy): { dense: number; bm25: number; final: number } {
  const qTerms = query.toLowerCase().split(/\s+/).filter((t) => t.length > 2);
  const cText = content.toLowerCase();

  let matches = 0;
  qTerms.forEach((t) => {
    if (cText.includes(t)) matches++;
  });

  const bm25 = Math.min(1.0, (matches / Math.max(1, qTerms.length)) * 0.95);
  // Dense similarity simulation (semantic overlap + baseline noise)
  const dense = Math.min(1.0, bm25 * 0.85 + 0.15 + (matches > 0 ? 0.2 : 0.05));

  let final = dense;
  if (strategy === "Hybrid (BM25+Dense)") {
    final = 0.5 * dense + 0.5 * bm25;
  } else if (strategy === "Code Syntax Aware") {
    final = matches > 0 ? Math.min(1.0, dense + 0.1) : dense * 0.5;
  } else if (strategy === "Multi-Doc Synthesis") {
    final = Math.min(1.0, (dense + bm25) / 1.8);
  }

  return {
    dense: Math.round(dense * 100) / 100,
    bm25: Math.round(bm25 * 100) / 100,
    final: Math.round(final * 100) / 100,
  };
}

// ─── Main Adaptive RAG Pipeline Execution ────────────────────────────────────

export async function runAdaptiveRagPipeline(
  query: string,
  subjectName: string,
  mode: RagMode,
  relevanceThreshold: number,
  approvedDocs: AppDocument[],
): Promise<RagResponse> {
  const intent = classifyIntent(query);
  const strategy = selectStrategy(intent, mode);

  const steps: PipelineStep[] = [
    { step: 1, title: "Intent Classification", detail: `Classified as "${intent}" → Strategy: ${strategy}`, status: "completed" },
    { step: 2, title: "Query Expansion & Normalization", detail: `Expanded: "${query} (${subjectName} context)"`, status: "completed" },
    { step: 3, title: "Vector & Hybrid Retrieval", detail: "Searching high-dimensional embeddings & BM25 index", status: "completed" },
    { step: 4, title: "Grounded Response & Guardrail Check", detail: "Synthesizing answer with citation verification", status: "completed" },
  ];

  // Off-topic rejection
  if (intent === "off_topic" || strategy === "Direct Rejection") {
    return {
      intent,
      strategy: "Direct Rejection",
      queryExpanded: query,
      retrievedChunks: [],
      confidenceScore: 100,
      hallucinationCheck: {
        passed: true,
        overlapScore: 1.0,
        reason: "Off-topic filter triggered. No knowledge retrieval attempted.",
      },
      answer: `I am your CSPIT CSE AI Learning Assistant. I am dedicated to helping you with your course syllabus (${subjectName} and related CSE topics). Please ask a question related to your studies!`,
      citations: [],
      followUpSuggestions: [
        `What are the core concepts in ${subjectName}?`,
        `Can you explain an important topic for ${subjectName}?`,
        `Show me exam revision notes for ${subjectName}`,
      ],
      shouldEscalate: false,
      pipelineSteps: steps,
    };
  }

  // Retrieve matching candidate chunks from mock pool + uploaded docs
  const subjectDocs = approvedDocs.filter(
    (d) => d.status === "approved"
  );

  const pool = MOCK_CHUNKS[subjectName] ?? MOCK_CHUNKS["Big Data Analytics"];
  const allCandidateChunks: RetrievedChunk[] = [];

  // Seed standard chunks for the subject
  pool.forEach((txt, idx) => {
    const scores = computeSimilarity(query, txt, strategy);
    allCandidateChunks.push({
      id: `chunk_seed_${idx}`,
      docId: `doc_seed_${idx}`,
      docName: `${subjectName} Unit ${idx + 1} Core Notes.pdf`,
      fileType: "pdf",
      subjectName,
      unit: `Unit ${idx + 1}`,
      pageNumber: (idx + 1) * 4 + 2,
      content: txt,
      similarityScore: scores.final,
      denseScore: scores.dense,
      bm25Score: scores.bm25,
    });
  });

  // Include user-uploaded approved docs
  subjectDocs.forEach((doc, idx) => {
    const txt = `[From uploaded material "${doc.name}"]: ${doc.topicTag ? `Topic: ${doc.topicTag}. ` : ""}${subjectName} course reference content covering ${doc.difficulty} difficulty material for Semester ${doc.semester}. Key concepts and structured explanations are provided.`;
    const scores = computeSimilarity(query, txt + " " + doc.name, strategy);
    allCandidateChunks.push({
      id: `chunk_uploaded_${doc.id}`,
      docId: doc.id,
      docName: doc.name,
      fileType: doc.fileType,
      subjectName,
      unit: doc.topicTag ? `Tag: ${doc.topicTag}` : `Unit ${idx + 1}`,
      pageNumber: 12,
      content: txt,
      similarityScore: scores.final,
      denseScore: scores.dense,
      bm25Score: scores.bm25,
    });
  });

  // Sort by similarity descending
  allCandidateChunks.sort((a, b) => b.similarityScore - a.similarityScore);

  // Filter by relevance threshold
  const filteredChunks = allCandidateChunks.filter((c) => c.similarityScore >= relevanceThreshold);
  const topChunks = (filteredChunks.length > 0 ? filteredChunks : allCandidateChunks).slice(0, 4);

  // Compute confidence score
  const avgSimilarity = topChunks.reduce((acc, c) => acc + c.similarityScore, 0) / Math.max(1, topChunks.length);
  const confidenceScore = Math.min(98, Math.round(avgSimilarity * 100 + 10));

  // Hallucination check
  const hallucinationPassed = avgSimilarity >= 0.45;
  const hallucinationReason = hallucinationPassed
    ? "Context overlap > 0.45 threshold. High grounding confidence."
    : "Low context overlap detected (< 0.45 threshold). Answer synthesized with disclaimer.";

  // Synthesize answer text with citations
  let answer = "";
  if (topChunks.length > 0 && topChunks[0].similarityScore > 0.3) {
    const top = topChunks[0];
    answer = `Based on your course materials in **${subjectName}** [1]:\n\n${top.content}\n\nKey takeaways:\n• **Core Concept**: ${top.unit} provides the theoretical framework for solving this problem efficiently.\n• **Application**: In practical systems, this ensures scalability, fault tolerance, and optimal resource utilization.`;
    if (topChunks.length > 1) {
      answer += `\n\nAdditionally, according to **${topChunks[1].docName}** [2]:\n"${topChunks[1].content.slice(0, 180)}..."`;
    }
  } else {
    answer = `Here is an explanation for **"${query}"** based on standard ${subjectName} principles:\n\nThe topic involves understanding the underlying system architecture, operational constraints, and algorithmic trade-offs. Note that matching chunks in the current uploaded knowledge base had a lower similarity score; please verify against your lecture slides.`;
  }

  // Citations
  const citations = topChunks.map((c, i) => ({
    id: `cit_${i + 1}`,
    docName: c.docName,
    page: c.pageNumber,
    unit: c.unit,
    chunkContent: c.content,
    similarity: c.similarityScore,
  }));

  // Follow-up recommendations
  const followUpSuggestions = [
    `Can you give a numerical example of ${query.slice(0, 20)}?`,
    `What are the advantages and disadvantages of this approach?`,
    `How is this asked in end-semester exams?`,
  ];

  const shouldEscalate = confidenceScore < 75 || !hallucinationPassed;

  return {
    intent,
    strategy,
    queryExpanded: `${query} [subject:${subjectName}, mode:${mode}]`,
    retrievedChunks: topChunks,
    confidenceScore,
    hallucinationCheck: {
      passed: hallucinationPassed,
      overlapScore: Math.round(avgSimilarity * 100) / 100,
      reason: hallucinationReason,
    },
    answer,
    citations,
    followUpSuggestions,
    shouldEscalate,
    pipelineSteps: steps,
  };
}
